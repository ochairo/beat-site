function cloneRecord(record: SyncSheetRecord): SyncSheetRecord {
  return {
    id: record.id,
    rank: record.rank,
    name: record.name,
    symbol: record.symbol,
    price: record.price,
    change1h: record.change1h,
    change24h: record.change24h,
    change7d: record.change7d,
    volume24h: record.volume24h,
    supply: record.supply,
    ath: record.ath,
    history: [...record.history],
  };
}

function cloneSnapshot(snapshot: SyncSheetSnapshot): SyncSheetSnapshot {
  return {
    revision: snapshot.revision,
    syncedAt: snapshot.syncedAt,
    records: snapshot.records.map(cloneRecord),
  };
}

export function createSyncSheetSnapshotSource(): () => SyncSheetSnapshot {
  let snapshotIndex = 0;

  return (): SyncSheetSnapshot => {
    const snapshot =
      SYNC_SHEET_SNAPSHOTS[
        Math.min(snapshotIndex, SYNC_SHEET_SNAPSHOTS.length - 1)
      ] ?? SYNC_SHEET_SNAPSHOTS[SYNC_SHEET_SNAPSHOTS.length - 1]!;

    snapshotIndex += 1;

    return cloneSnapshot(snapshot);
  };
}
